@dataclass
class RequestPaymentRequestParameters:
    """
    Dataclass for Request Payment request parameters.

    Attributes:
        `merchant_reference (str)`: Unique identifier for this payment request.
        `network_code (str)`: Mobile telecomunications network we are
            requesting the transaction from.
        `mobile_number (str)`: Mobile number from which funds are being
            transfered.
        `receiver_account_number (str)`: Unique number identifying a customer
            whose wallet is to be loaded with funds.
        `amount (str)`: Amount of money being loaded to the customer's wallet.
        `transaction_fee (str)`: This the amount charged as the transaction fee
            for wallet topup.
        `currency_code (str)`: Standardization that defines alpha codes and
            numeric codes for the representation of currencies.
        `merchant_code (str)`: A unique number assigned to an
            organization/merchant registered with ViewTech, through which
            payment is received (can be Paybill or Till number).
        `transaction_description`: A brief description of the purpose of
            topping up the balance.
        `callback_url`: This is the URL where SasaPay will send the results
            after the payment process is initiated.
    """

    merchant_reference: str
    network_code: str
    mobile_number: str
    receiver_account_number: str
    amount: str
    transaction_fee: str
    currency_code: str
    merchant_code: str
    transaction_description: str
    callback_url: str

    def to_dict(self):
        return {
            "merchantReference": self.merchant_reference,
            "networkCode": self.network_code,
            "mobileNumber": self.mobile_number,
            "receiverAccountNumber": self.receiver_account_number,
            "amount": self.amount,
            "transactionFee": self.transaction_fee,
            "currencyCode": self.currency_code,
            "merchantCode": self.merchant_code,
            "transactionDesc": self.transaction_description,
            "callbackUrl": self.callback_url,
        }


