@dataclass
class RequestPaymentCallbackResultsParameters:
    """
    Dataclass representing the callback results send by Sasapay after a Request
    Payment request has been completed.

    Attributes:
        `merchant_request_id (str)`: The unique id sent with the transaction
            request from the Merchant system.
        `checkout_request_id (str)`: This is a unique SasaPay transaction ID
            for every payment request. Same value is sent to the customer over
            SMS upon successful processing.
        `payment_request_id (str)`: Unique identifier for a payment request
            transaction.
        `result_code (str)`: The numeric status of the results, sent to the
            callback url
        `result_description (str)`: This is a message from the API that gives
            the status of the request processing and usually maps to a specific
            result code value.
        `source_channel (str)`: Mobile money provider that was part of the
            transaction.
        `transaction_amount (str)`: This is the amount that was transacted. It
            is usually returned under the ResultParameter array.
        `bill_reference_number (str)`: This is a unique SasaPay transaction ID
            for every payment request. Same value is sent to the customer over
            SMS upon successful processing. It is usually returned under the
            ResultParameter array.
        `transaction_date (str)`: This is the date and time that the
            transaction completed SasaPay.
        `customer_mobile (str)`: This mobile number from where the funds are
            requested.
        `transaction_code (str)`: Unique code for this transaction.
        `third_party_transaction_id (str)`: This is the transaction refrence
            from third party systems SasaPay.
    """

    merchant_request_id: str
    checkout_request_id: str
    payment_request_id: str
    result_code: str
    result_description: str
    source_channel: str
    transaction_amount: str
    bill_reference_number: str
    transaction_date: str
    customer_mobile: str
    transaction_code: str
    third_party_transaction_id: str

    def to_dict(self):
        return {
            "MerchantRequestID": self.merchant_request_id,
            "CheckoutRequestID": self.checkout_request_id,
            "PaymentRequestID": self.payment_request_id,
            "ResultCode": self.result_code,
            "ResultDesc": self.result_description,
            "SourceChannel": self.source_channel,
            "TransAmount": self.transaction_amount,
            "BillRefNumber": self.bill_reference_number,
            "TransactionDate": self.transaction_date,
            "CustomerMobile": self.customer_mobile,
            "TransactionCode": self.transaction_code,
            "ThirdPartyTransID": self.third_party_transaction_id,
        }


