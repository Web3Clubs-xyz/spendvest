from dataclasses import dataclass
from typing_extensions import TypedDict


@dataclass
class PersonalOnboardingRequestParameters:
    """
    Dataclass for personal onboarding request parameters.

    Attributes:
        merchant_code (`str`): A unique number assigned to an
            organization/merchant registered with ViewTech, through which payment
            is received (can be Paybill or Till number).
        first_name (`str`): The first name of the customer as it appears on the
            identity card or passport
        middle_name (`str`): The middle name of the customer as it appears on
            their identity card of passport
        last_name (`str`): The last name of the customer as it appears on their
            identity card.
        country_code (`str`): This is the country calling code.
        mobile_number (`str`): This is the mobile number identifying merchant
            beneficiary and is required during registration.
        document_number (`str`): This is the number on the identification
            document type.
        document_type (`str`): This is the type of identifying documentation
            for the customer.
        email (`str`): The customer's email.
        callback_url (`str`): This is the link where sasapay will send the data
            about beneficiary status during onboarding process.This data can be
            used by the mechant to update beneficiary status on merchant system.
    """

    merchant_code: str
    first_name: str
    middle_name: str
    last_name: str
    country_code: str
    mobile_number: str
    document_number: str
    document_type: str
    email: str
    callback_url: str


